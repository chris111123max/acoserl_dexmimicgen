"""Audit saved LIVE worker actions/RGB n-step endpoints and optimizer moments.
No physics, optimizer updates or synthetic rewards are generated by this audit.
"""
import argparse,json,hashlib
from pathlib import Path
import numpy as np,torch
from acoserl.ascend_data import replay
from acoserl.dynamic_demo import DynamicDemo
from acoserl.transition_semantics import source_code,TASK_INTERVENTION_SOURCES
ROOT=Path(__file__).resolve().parents[2]
p=argparse.ArgumentParser();p.add_argument('--tag',required=True);a=p.parse_args()
out=ROOT/'outputs/ascend16'/a.tag;result=json.loads((out/'summary.json').read_text());assert result['status']=='completed',result.get('error')
c=result['counters'];cfg=result['config'];assert cfg['purpose']=='integration' and cfg['collector_protocol']=='autoserl_baseline_v1'
assert cfg['num_envs']==16 and cfg['startup_groups']==[4]*4 and cfg['utd']==1 and cfg['n_step']==3
assert c['valid_real_steps']+c['evaluation_interactions']<=2048 and c['actor_updates']==c['critic_updates']>16
assert result['restoration_checks']['optimizer_continuation_update'] and result['offline_rows']==224
manifest=json.loads((out/'tested_source_manifest.json').read_text())['sha256']
assert all(hashlib.sha256((ROOT/name).read_bytes()).hexdigest()==sha for name,sha in manifest.items()),'source changed during integration'
raw={};counts={};worker_stats=[];partial=0;rejected=0;actor_proposals=0;motion=0;handbacks=0
for env in range(16):
 stats={'env_id':env,'sources':{},'complete':0,'partial':0,'rejected':0,'handbacks':0,'policy_proposals':0,'nonzero_motion':0}
 for line in (out/'workers'/f'env{env:02d}.jsonl').open():
  d=json.loads(line)
  if d['event']!='step':continue
  if not d.get('diagnostic_preparation'):actor_proposals+=1;stats['policy_proposals']+=1
  if not d['executed']:
   rejected+=1;stats['rejected']+=1
   if d.get('partial_physics_step'):partial+=1;stats['partial']+=1
   continue
  key=(env,d['episode_id'],d['frame']);assert key not in raw;raw[key]=d
  source=d['action_source'];counts[source]=counts.get(source,0)+1;stats['sources'][source]=stats['sources'].get(source,0)+1;stats['complete']+=1
  assert d['physics_time_advanced']>0 and abs(d['physics_time_advanced']-.05)<1e-7
  assert float(d['reward'])==float(d.get('success',False)),key
  roles=d['arm_control'];assert sum(roles['expert_action_mask'])<=7
  if source.startswith('Constrained_'):assert not any(roles['expert_action_mask'])
  if d.get('nonzero_physical_motion'):motion+=1;stats['nonzero_motion']+=1
  if (d.get('recovery_result') or {}).get('safe_handback'):handbacks+=1;stats['handbacks']+=1
 worker_stats.append(stats)
assert all(s['policy_proposals']>0 and s['complete']>0 for s in worker_stats)
assert len(raw)==c['valid_real_steps'] and partial==c['partial_action_attempts']
ck=Path(result['checkpoint']);on=replay(cfg['online_capacity'],128);on.loads(ck/'online_buffer');off=replay(224,128);off.loads(ck/'offline_buffer')
assert len(on)==len(raw) and len(off)==224
stored={(int(r['env_id']),int(r['episode']),int(r['frame'])):r for r in on[:]};assert set(stored)==set(raw)
image_links=0
for key,row in stored.items():
 d=raw[key];n=int(row['steps_to_next_obs']);assert 1<=n<=3
 assert torch.max(abs(row['action']-torch.tensor(d['executed_action'])))<2e-6,key
 assert torch.max(abs(row['policy_action_proposed']-torch.tensor(d['policy_action'])))<2e-6,key
 assert int(row['action_source'])==(12 if d['action_source']=='DiagnosticPreparation' else source_code(d['auto_intervention']['mode']))
 assert torch.equal(row['expert_action_mask'],torch.tensor(d['arm_control']['expert_action_mask']))
 chain=[raw[(key[0],key[1],key[2]+i)] for i in range(n)]
 expected=sum(.99**i*r['reward'] for i,r in enumerate(chain));assert abs(float(row['next','reward'])-expected)<1e-6
 assert abs(float(row['gamma'])-.99**n)<1e-6
 future=stored.get((key[0],key[1],key[2]+n))
 if future is not None:
  for cam in row['obs'].keys():assert torch.equal(row['next','obs',cam],future['obs',cam]),(key,cam)
  image_links+=1
 assert bool(row['nonterminal'])==bool(row['next','bootstrap_allowed'])
 if int(row['next','boundary_kind']) in (1,3,4,5,8):assert not bool(row['nonterminal'])
bank=DynamicDemo(cfg['manager_config']['dynamic_capacity'],original_fraction=cfg['manager_config']['original_demo_fraction'],original_quota=96,positive_quota=2,admission_mode='official');bank.load(ck/'dynamic_demo',discard_pending=False)
assert len(bank.buffer)>0 and bank.stats['safe_handbacks']>0
for row in bank.buffer[:]:
 assert int(row['action_source']) in TASK_INTERVENTION_SOURCES and 0<int(row['expert_action_mask'].sum())<=7
 assert bool(row['quality_validated']) and float(row['quality_error_before']-row['quality_error_after'])>1e-6
 key=(int(row['env_id']),int(row['episode']),int(row['frame']));assert key in stored
 assert torch.equal(row['action'],stored[key]['action'])
 n=int(row['steps_to_next_obs']);end=raw[(key[0],key[1],key[2]+n-1)]
 for i in range(n):assert raw[(key[0],key[1],key[2]+i)]['action_source'].startswith(('Recover_','Guide_'))
model=torch.load(ck/'model.pt',map_location='cpu',weights_only=False)
assert all(torch.isfinite(v).all() for v in model['agent_state_dict'].values())
optim=model['optimizer_state_dict']['actor_opt'];ids=sum([x['params'] for x in optim['param_groups']],[])
actor_names=[k for k in model['agent_state_dict'] if k.startswith('actor.')]
# Saved Adam moments of the 14-output weight demonstrate gradients reached both grippers.
outputs=[]
for param,state in optim['state'].items():
 moment=state.get('exp_avg_sq')
 if isinstance(moment,torch.Tensor) and moment.ndim==2 and moment.shape[0]==14:
  outputs.append(dict(shape=list(moment.shape),per_output_second_moment=moment.sum(1).tolist(),all_outputs_have_gradient_history=bool((moment.sum(1)>0).all())))
assert outputs and all(x['all_outputs_have_gradient_history'] for x in outputs)
audit=dict(passed=True,real_live_rows=len(raw),online_rows=len(on),original_rows=len(off),dynamic_rows=len(bank.buffer),dynamic_stats=bank.stats,source_counts=counts,workers=worker_stats,actual_actor_proposals=actor_proposals,nonzero_motion_steps=motion,safe_handbacks=handbacks,rejected_attempts=rejected,partial_attempts=partial,nstep_rgb_links_exact=image_links,no_cross_env_episode=True,executed_actions_exact=True,per_arm_expert_masks_exact=True,all_parameters_finite=True,gripper_gradient_history=outputs,source_manifest_exact=True,checkpoint_reload=result['restoration_checks'],new_physics_steps=0,new_gradient_updates=0)
(out/'integration_audit.json').write_text(json.dumps(audit,indent=2)+'\n');print(json.dumps(audit))
